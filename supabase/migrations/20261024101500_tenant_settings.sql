-- Configurable lookup tables were keyed globally. Scope their natural keys
-- and all incoming references to the establishment.
DO $$ DECLARE item record; fk record; BEGIN
  CREATE TEMP TABLE tenant_lookup_fk (
    constraint_name text, child_name text, child_column text,
    parent_name text, parent_column text, on_update text, on_delete text
  ) ON COMMIT DROP;
  FOR item IN SELECT t.relname AS table_name, pk.conname AS pk_name, a.attname AS key_name
    FROM pg_constraint pk JOIN pg_class t ON t.oid=pk.conrelid
    JOIN pg_namespace n ON n.oid=t.relnamespace
    JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=pk.conkey[1]
    WHERE n.nspname='public' AND pk.contype='p' AND cardinality(pk.conkey)=1
      AND a.attname IN ('key','classification_key','level','min_score')
      AND EXISTS(SELECT 1 FROM pg_attribute tenant WHERE tenant.attrelid=t.oid
        AND tenant.attname='establishment_id')
      AND t.relname NOT IN ('plans','module_catalog','operation_code_counters',
        'process_code_counters','module_code_counters','document_code_counters')
  LOOP
    DELETE FROM tenant_lookup_fk;
    INSERT INTO tenant_lookup_fk
    SELECT f.conname, child.relname, child_col.attname, item.table_name, item.key_name,
      f.confupdtype::text, f.confdeltype::text
    FROM pg_constraint f JOIN pg_class child ON child.oid=f.conrelid
      JOIN pg_attribute child_col ON child_col.attrelid=child.oid AND child_col.attnum=f.conkey[1]
    WHERE f.contype='f' AND f.confrelid=format('public.%I',item.table_name)::regclass
      AND cardinality(f.conkey)=1 AND cardinality(f.confkey)=1
      AND f.confkey[1]=(SELECT attnum FROM pg_attribute
        WHERE attrelid=f.confrelid AND attname=item.key_name);
    FOR fk IN SELECT * FROM tenant_lookup_fk LOOP
      EXECUTE format('ALTER TABLE public.%I DROP CONSTRAINT %I',fk.child_name,fk.constraint_name);
    END LOOP;
    EXECUTE format('ALTER TABLE public.%I DROP CONSTRAINT %I',item.table_name,item.pk_name);
    EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I PRIMARY KEY (establishment_id,%I)',
      item.table_name,item.pk_name,item.key_name);
    FOR fk IN SELECT * FROM tenant_lookup_fk LOOP
      EXECUTE format('ALTER TABLE public.%I ADD CONSTRAINT %I FOREIGN KEY (establishment_id,%I) REFERENCES public.%I(establishment_id,%I) ON UPDATE %s ON DELETE %s',
        fk.child_name,fk.constraint_name,fk.child_column,fk.parent_name,fk.parent_column,
        CASE fk.on_update WHEN 'c' THEN 'CASCADE' WHEN 'n' THEN 'SET NULL'
          WHEN 'd' THEN 'SET DEFAULT' WHEN 'r' THEN 'RESTRICT' ELSE 'NO ACTION' END,
        CASE fk.on_delete WHEN 'c' THEN 'CASCADE' WHEN 'n' THEN 'SET NULL'
          WHEN 'd' THEN 'SET DEFAULT' WHEN 'r' THEN 'RESTRICT' ELSE 'NO ACTION' END);
    END LOOP;
  END LOOP;
END $$;

-- Each tenant can choose its own default status, classification and color.
DO $$ DECLARE item record; BEGIN
  FOR item IN SELECT t.relname AS table_name, i.relname AS index_name,
      a.attname AS flag_name FROM pg_class i
    JOIN pg_index ix ON ix.indexrelid=i.oid
    JOIN pg_class t ON t.oid=ix.indrelid
    JOIN pg_namespace n ON n.oid=t.relnamespace
    JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=ix.indkey[0]
    WHERE n.nspname='public' AND (i.relname LIKE '%_single_default_idx'
      OR i.relname LIKE '%_single_initial_idx')
  LOOP
    EXECUTE format('DROP INDEX public.%I',item.index_name);
    EXECUTE format('CREATE UNIQUE INDEX %I ON public.%I(establishment_id,%I) WHERE %I',
      item.index_name,item.table_name,item.flag_name,item.flag_name);
  END LOOP;
END $$;


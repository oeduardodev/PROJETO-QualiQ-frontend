-- Codes remain generated by shared counters, while uniqueness is checked
-- within the owning establishment.
DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['processes','slas','risks','indicators','tickets',
    'helpdesk_tickets','documents','action_plans'] LOOP
    IF to_regclass(format('public.%I',t)) IS NULL THEN CONTINUE; END IF;
    IF NOT EXISTS(SELECT 1 FROM information_schema.columns WHERE table_schema='public'
      AND table_name=t AND column_name='code') THEN CONTINUE; END IF;
    EXECUTE format('DROP INDEX IF EXISTS public.%I',t||'_code_unique');
    EXECUTE format('CREATE UNIQUE INDEX %I ON public.%I(establishment_id,code) WHERE code IS NOT NULL',
      t||'_code_unique',t);
  END LOOP;
END $$;

-- Copy editable text-keyed settings (and document hierarchy levels) from
-- Homologation when a new establishment is created. IDs in operational data
-- are never copied.
CREATE OR REPLACE FUNCTION public.bootstrap_establishment_settings()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path='' AS $$
DECLARE item record; columns_sql text; values_sql text;
BEGIN
  FOR item IN SELECT t.relname AS table_name FROM pg_class t
    JOIN pg_namespace n ON n.oid=t.relnamespace
    JOIN pg_constraint pk ON pk.conrelid=t.oid AND pk.contype='p'
    JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=pk.conkey[1]
    WHERE n.nspname='public' AND cardinality(pk.conkey)=2
      AND pk.conkey[1]=(SELECT attnum FROM pg_attribute
        WHERE attrelid=t.oid AND attname='establishment_id')
      AND a.attname='establishment_id'
      AND t.relname NOT IN ('establishment_modules','ai_monthly_usage')
      AND EXISTS(SELECT 1 FROM pg_attribute k WHERE k.attrelid=t.oid
        AND k.attnum=pk.conkey[2] AND k.attname IN ('key','classification_key','level','min_score'))
  LOOP
    SELECT string_agg(format('%I',attname),',' ORDER BY attnum),
      string_agg(CASE WHEN attname='establishment_id' THEN '$1'
        ELSE format('%I',attname) END,',' ORDER BY attnum)
    INTO columns_sql,values_sql
    FROM pg_attribute WHERE attrelid=format('public.%I',item.table_name)::regclass
      AND attnum>0 AND NOT attisdropped AND attgenerated='';
    EXECUTE format('INSERT INTO public.%I(%s) SELECT %s FROM public.%I WHERE establishment_id=$2',
      item.table_name,columns_sql,values_sql,item.table_name)
      USING NEW.id,'00000000-0000-4000-8000-000000000001'::uuid;
  END LOOP;
  RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.bootstrap_establishment_settings() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER bootstrap_establishment_settings AFTER INSERT ON public.establishments
FOR EACH ROW WHEN (NEW.id<>'00000000-0000-4000-8000-000000000001'::uuid)
EXECUTE FUNCTION public.bootstrap_establishment_settings();
